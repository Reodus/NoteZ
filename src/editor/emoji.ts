/** Emoji whose name contains `q` (prefix matches first). */
export function findEmoji(q: string, limit = 60): [string, string][] {
  const s = q.toLowerCase();
  const starts = EMOJI.filter(([n]) => n.startsWith(s));
  const has = EMOJI.filter(([n]) => !n.startsWith(s) && n.includes(s));
  return [...starts, ...has].slice(0, limit);
}
